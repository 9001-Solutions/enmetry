--[[
* Regenerates every vendored enmity table under addon/data/.
*
*   luajit tools/gentables.lua                   from the pinned sources
*   luajit tools/gentables.lua --fetch-wiki      re-snapshot the wiki first
*   luajit tools/gentables.lua --lsb D:/LandSandBoat --out some/dir
*
* Run from the repo root.  Sources:
*
*   LandSandBoat at LSB_COMMIT, read from git objects, so the checkout can be
*   on any branch.  Found at ../LandSandBoat, $ENMETRY_LSB, or --lsb.
*
*   HorizonXI wiki snapshots in tools/tables/sources/horizonwiki/.
*
*   tools/tables/horizon.lua, the hand-curated rules.
--]]

package.path = './tools/?.lua;' .. package.path;

